import { createHash } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const outDir = path.join(projectRoot, "out");
const basePath = normalizeBasePath(process.env.NEXT_PUBLIC_BASE_PATH ?? "");

function normalizeBasePath(value) {
  const trimmed = value.trim();
  if (!trimmed || trimmed === "/") return "";

  const withLeadingSlash = trimmed.startsWith("/")
    ? trimmed
    : `/${trimmed}`;

  return withLeadingSlash.replace(/\/+$/, "");
}

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name);

    if (entry.isSymbolicLink()) {
      throw new Error(
        `Symbolic links are not supported in the Pages artifact: ${absolutePath}`,
      );
    }

    if (entry.isDirectory()) {
      files.push(...(await walk(absolutePath)));
    } else if (entry.isFile()) {
      files.push(absolutePath);
    }
  }

  return files;
}

function toPublicUrl(relativePath) {
  const encodedPath = relativePath
    .split(path.sep)
    .map((segment) => encodeURIComponent(segment))
    .join("/");

  return `${basePath}/${encodedPath}`;
}

try {
  const outStats = await fs.stat(outDir);
  if (!outStats.isDirectory()) throw new Error();
} catch {
  throw new Error(
    "The out/ directory does not exist. Run `next build` with `output: \"export\"` first.",
  );
}

const allFiles = await walk(outDir);
const relativeFiles = allFiles
  .map((file) => path.relative(outDir, file))
  .filter((file) => file !== "sw.js" && file !== ".nojekyll")
  .filter((file) => !file.endsWith(".map"))
  .sort((a, b) => a.localeCompare(b));

if (!relativeFiles.includes("index.html")) {
  throw new Error("out/index.html is missing; the static export is incomplete.");
}

const revisionHash = createHash("sha256");
for (const relativeFile of relativeFiles) {
  revisionHash.update(relativeFile);
  revisionHash.update(await fs.readFile(path.join(outDir, relativeFile)));
}

const revision = revisionHash.digest("hex").slice(0, 16);
const appRoot = `${basePath}/`;
const appShell = `${basePath}/index.html`;
const precacheUrls = [
  appRoot,
  ...relativeFiles.map(toPublicUrl),
].filter((value, index, values) => values.indexOf(value) === index);

const serviceWorker = `/* Generated by scripts/prepare-pages-pwa.mjs. Do not edit out/sw.js directly. */
const CACHE_PREFIX = "identity-navigator-pages-";
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(revision)};
const APP_SHELL = ${JSON.stringify(appShell)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
            .map((name) => caches.delete(name)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const requestUrl = new URL(request.url);
  if (requestUrl.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then(async (response) => {
          if (response.ok) {
            const cache = await caches.open(CACHE_NAME);
            await cache.put(request, response.clone());
          }
          return response;
        })
        .catch(async () => {
          return (await caches.match(request)) ?? caches.match(APP_SHELL);
        }),
    );
    return;
  }

  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then(async (cached) => {
      if (cached) return cached;

      const response = await fetch(request);
      if (response.ok) {
        const cache = await caches.open(CACHE_NAME);
        await cache.put(request, response.clone());
      }
      return response;
    }),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
});
`;

await fs.writeFile(path.join(outDir, "sw.js"), serviceWorker, "utf8");
await fs.writeFile(path.join(outDir, ".nojekyll"), "", "utf8");

console.log(
  `Prepared ${precacheUrls.length} offline URLs for GitHub Pages ` +
    `(cache ${revision}, base path ${basePath || "/"}).`,
);
